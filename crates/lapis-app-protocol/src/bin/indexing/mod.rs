use lapis_app_protocol::indexing::*;
use ts_rs::{Config, TS};
pub(super) fn declarations(config: &Config) -> Vec<String> {
    vec![
        ProjectionContribution::decl(config),
        search::SearchProviderContribution::decl(config),
        search::SearchIndexingSelection::decl(config),
        IndexingCommand::decl(config),
        IndexingPhase::decl(config),
        IndexingStatus::decl(config),
        ContributionPlacement::decl(config),
        ContributionStatus::decl(config),
        IndexingValue::decl(config),
    ]
}
pub(super) fn typescript(config: &Config) -> String {
    format!(
        "// Generated by pnpm protocol:generate. Do not edit.\nimport type {{ SearchChunkingSettings }} from './native-database-protocol';\n{}\n",
        declarations(config)
            .iter()
            .map(|item| format!("export {item}"))
            .collect::<Vec<_>>()
            .join("\n")
    )
}
