use lapis_app_protocol::queues::*;
use ts_rs::{Config, TS};
pub(super) fn declarations(config: &Config) -> [String; 12] {
    [
        QueueRecipient::decl(config),
        QueueModel::decl(config),
        QueueAgent::decl(config),
        QueueThinking::decl(config),
        QueueCaptureTarget::decl(config),
        QueueSelection::decl(config),
        QueueAccept::decl(config),
        QueuePhase::decl(config),
        QueueEntry::decl(config),
        QueueRecord::decl(config),
        QueueCommand::decl(config),
        QueueValue::decl(config),
    ]
}
pub(super) fn typescript(config: &Config) -> String {
    format!(
        "// Generated by pnpm protocol:generate. Do not edit.\nexport const QUEUE_REQUEST_LIMIT = {QUEUE_REQUEST_LIMIT} as const;\nexport const QUEUE_RECORD_LIMIT = {QUEUE_RECORD_LIMIT} as const;\n{}\n",
        declarations(config)
            .iter()
            .map(|v| format!("export {v}"))
            .collect::<Vec<_>>()
            .join("\n")
    )
}
