pub(super) fn typescript(config: &Config) -> String {
    let mut declarations = vec![lapis_app_protocol::TextSnapshot::decl(config)];
    declarations.extend(self::declarations(config));
    format!(
        "// Generated by pnpm protocol:generate. Do not edit.\n{}\n",
        declarations
            .iter()
            .map(|value| format!("export {value}"))
            .collect::<Vec<_>>()
            .join("\n")
    )
}
