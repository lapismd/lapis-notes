use lapis_app_protocol::history_index::*;
use ts_rs::{Config, TS};

pub(super) fn declarations(config: &Config) -> Vec<String> {
    vec![
        HistoryExpression::decl(config),
        HistoryIndexQuery::decl(config),
        HistoryIndexCommand::decl(config),
        HistoryIndexProgress::decl(config),
        HistoryCheckpoint::decl(config),
        HistorySavedRevision::decl(config),
        HistoryIndexRecord::decl(config),
        HistoryIndexHit::decl(config),
        HistoryIndexPage::decl(config),
        HistoryIndexContext::decl(config),
        HistoryIndexValue::decl(config),
    ]
}

pub(super) fn typescript(config: &Config) -> String {
    format!(
        "// Generated by pnpm protocol:generate. Do not edit.\n{}\n",
        declarations(config)
            .iter()
            .map(|item| format!("export {item}"))
            .collect::<Vec<_>>()
            .join("\n")
    )
}
