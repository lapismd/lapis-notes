import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const start = "<!-- migration-tasks:start -->";
const end = "<!-- migration-tasks:end -->";
const statuses = [
  "Working",
  "Waiting",
  "Deferred",
  "Source complete",
  "Complete",
];
const collator = new Intl.Collator("en", { numeric: true });

export function validateLedger(ledger, root) {
  const errors = [];
  const timestamp = ledger?.updated;
  const parsed =
    typeof timestamp === "string"
      ? Date.parse(timestamp.replace(" UTC", "Z").replace(" ", "T"))
      : NaN;
  if (
    typeof timestamp !== "string" ||
    !/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} UTC$/u.test(timestamp) ||
    !Number.isFinite(parsed) ||
    `${new Date(parsed).toISOString().slice(0, 19).replace("T", " ")} UTC` !==
      timestamp
  )
    errors.push("The ledger needs a valid UTC date/time in updated.");
  if (!Array.isArray(ledger?.tasks) || !ledger.tasks.length)
    return [...errors, "The ledger needs a nonempty tasks array."];
  const ids = new Set();
  for (const task of ledger.tasks) {
    if (!task || typeof task !== "object") {
      errors.push("Each task must be an object.");
      continue;
    }
    if (typeof task.id !== "string" || !/^R\d+(?:\.\d+)*$/u.test(task.id))
      errors.push(`Invalid task ID: ${task.id}.`);
    if (ids.has(task.id)) errors.push(`Duplicate task ID: ${task.id}.`);
    ids.add(task.id);
    if (!statuses.includes(task.status))
      errors.push(`${task.id}: unknown gate status ${task.status}.`);
    for (const key of ["area", "work", "detail"])
      if (
        typeof task[key] !== "string" ||
        !task[key].trim() ||
        /[\r\n]/u.test(task[key])
      )
        errors.push(
          `${task.id}: ${key} must be nonempty single-line Markdown.`,
        );
    if (
      typeof task.spec !== "string" ||
      !/^spec\/src\/(?:[a-z0-9-]+\/)*[a-z0-9-]+\.md#ln-[a-z]+-\d{3}$/u.test(
        task.spec,
      )
    ) {
      errors.push(`${task.id}: link to an owning canonical spec requirement.`);
      continue;
    }
    const [file, anchor] = task.spec.split("#");
    try {
      if (
        !readFileSync(resolve(root, file), "utf8").includes(
          `<a id="${anchor}"></a>`,
        )
      )
        errors.push(`${task.id}: missing spec anchor ${task.spec}.`);
    } catch {
      errors.push(`${task.id}: missing spec file ${file}.`);
    }
  }
  return errors;
}

export async function renderTasks(tasks) {
  const groups = [];
  for (const status of statuses) {
    const rows = tasks
      .filter((task) => task.status === status)
      .sort((a, b) => collator.compare(a.id, b.id));
    if (!rows.length) continue;
    const cell = (value) => value.replaceAll("|", "\\|");
    const table = [
      "| Task ID | Area | Work | Evidence or next gate |",
      "| --- | --- | --- | --- |",
      ...rows.map(
        (task) =>
          `| [${task.id}](${task.spec}) | ${cell(task.area)} | ${cell(task.work)} | ${cell(task.detail)} |`,
      ),
    ].join("\n");
    groups.push(`### Gate status: ${status}\n\n${table}`);
  }
  return format(
    `${start}\n\n<!-- Generated by pnpm progress:generate from spec/migration-progress.json. Do not edit these tables. -->\n\n[Task source ledger](spec/migration-progress.json) · Regenerate with\n\`pnpm progress:generate\`; verify with \`pnpm check:progress\`.\n\nTask IDs link to their owning canonical specification. Tables group gates, not\nexecution order; the [full plan](RUST_CORE_MIGRATION_PLAN.md#ordered-implementation)\nretains the dependencies. Source complete qualifies shared Rust source only,\nnot host adoption or native/hosted application acceptance.\n\n${groups.join("\n\n")}\n\n${end}\n`,
    { parser: "markdown" },
  );
}

export async function projectMigration(source, ledger) {
  if (
    source.split(start).length !== 2 ||
    source.split(end).length !== 2 ||
    source.indexOf(end) < source.indexOf(start)
  )
    throw new Error("MIGRATION.md needs one complete migration-tasks block.");
  const stamp = /^Last updated \*\*[^\n]+ UTC\*\*/gmu;
  if ([...source.matchAll(stamp)].length !== 1)
    throw new Error("MIGRATION.md needs one UTC last-updated stamp.");
  const before = source.slice(0, source.indexOf(start));
  const after = source.slice(source.indexOf(end) + end.length);
  return `${before}${(await renderTasks(ledger.tasks)).trimEnd()}${after}`.replace(
    stamp,
    `Last updated **${ledger.updated}**`,
  );
}

export async function run(root, write = false) {
  const ledger = JSON.parse(
    readFileSync(resolve(root, "spec/migration-progress.json"), "utf8"),
  );
  const errors = validateLedger(ledger, root);
  if (errors.length) throw new Error(errors.join("\n"));
  const path = resolve(root, "MIGRATION.md");
  const source = readFileSync(path, "utf8");
  const generated = await projectMigration(source, ledger);
  if (write) {
    writeFileSync(path, generated);
    return `Generated MIGRATION.md (${ledger.tasks.length} tasks).`;
  }
  if (source !== generated)
    throw new Error("MIGRATION.md is stale; run pnpm progress:generate.");
  return `Migration progress passes (${ledger.tasks.length} tasks; grouped, sorted and spec-linked).`;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const args = process.argv.slice(2);
  try {
    if (args.length > 1 || args.some((arg) => arg !== "--write"))
      throw new Error("Usage: node scripts/migration-progress.mjs [--write]");
    console.log(
      await run(
        fileURLToPath(new URL("../", import.meta.url)),
        args.includes("--write"),
      ),
    );
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
