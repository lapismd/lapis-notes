import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const apiRoot = path.join(root, "packages/api");
const metadata = JSON.parse(
  await readFile(path.join(apiRoot, "package.json"), "utf8"),
);
const configured = JSON.parse(
  await readFile(
    path.join(root, "scripts/plugin-host-modules.config.json"),
    "utf8",
  ),
);
const registry = Object.fromEntries(
  Object.entries(configured).filter(
    ([, entry]) => entry.packageName !== metadata.name || entry.aliasOf,
  ),
);
const svelteMetadata = JSON.parse(
  await readFile(path.join(root, "node_modules/svelte/package.json"), "utf8"),
);
if (svelteMetadata.version !== metadata.peerDependencies.svelte)
  throw new Error(
    `Renderer ABI requires Svelte ${metadata.peerDependencies.svelte}; installed ${svelteMetadata.version}.`,
  );
const rendererSources = [
  "svelte",
  "svelte/animate",
  "svelte/attachments",
  "svelte/easing",
  "svelte/events",
  "svelte/legacy",
  "svelte/motion",
  "svelte/reactivity",
  "svelte/reactivity/window",
  "svelte/store",
  "svelte/transition",
  "svelte/internal/client",
  "svelte/internal/disclose-version",
  "svelte/internal/flags/async",
  "svelte/internal/flags/legacy",
  "svelte/internal/flags/tracing",
];
for (const source of rendererSources) {
  const subpath =
    source === "svelte" ? "." : "." + source.slice("svelte".length);
  if (!svelteMetadata.exports[subpath])
    throw new Error(
      `Svelte ${svelteMetadata.version} has no renderer export ${source}.`,
    );
  const specifier = `svelte/renderer/${svelteMetadata.version}${source.slice("svelte".length)}`;
  registry[specifier] = {
    entry: source,
    moduleId: specifier.replaceAll("/", "-").replaceAll(".", "-"),
    packageName: "svelte",
    platforms: ["web", "electron-renderer"],
    public: true,
    source: "renderer-abi",
    specifier,
    version: svelteMetadata.version,
  };
}
async function discover(directory, prefix = "") {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const subpath = prefix + entry.name;
    const children = await readdir(path.join(directory, entry.name), {
      withFileTypes: true,
    });
    if (children.some((child) => child.isFile() && child.name === "index.ts"))
      found.push("./" + subpath);
    found.push(
      ...(await discover(path.join(directory, entry.name), subpath + "/")),
    );
  }
  return found;
}
const exports = Object.keys(metadata.exports).filter(
  (key) => !key.includes("*"),
);
if (metadata.exports["./*"]?.import === "./dist/components/*/index.js") {
  exports.push(...(await discover(path.join(apiRoot, "src/lib/components"))));
}
for (const subpath of exports) {
  const specifier = metadata.name + (subpath === "." ? "" : subpath.slice(1));
  const previous = configured[specifier];
  registry[specifier] = {
    ...(previous ?? {}),
    entry: specifier,
    moduleId:
      previous?.moduleId ?? specifier.replace(/^@/, "").replaceAll("/", "-"),
    packageName: metadata.name,
    platforms: previous?.platforms ?? ["web", "electron-renderer"],
    public: true,
    source: "package-json-export",
    specifier,
    version: metadata.version,
  };
}
function sorted(value) {
  if (Array.isArray(value)) return value.map(sorted);
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, sorted(value[key])]),
    );
  return value;
}
const source =
  "// Generated by scripts/generate-plugin-host-modules.mjs. Do not edit by hand.\n\n" +
  "export const pluginHostModuleRegistry = " +
  JSON.stringify(sorted(registry), null, 2) +
  " as const;\n\n" +
  "export const pluginHostModuleSpecifiers = Object.keys(pluginHostModuleRegistry) as Array<keyof typeof pluginHostModuleRegistry>;\n\n" +
  "export function isPluginHostModuleSpecifier(value: string): value is keyof typeof pluginHostModuleRegistry {\n  return Object.hasOwn(pluginHostModuleRegistry, value);\n}\n\nexport default pluginHostModuleRegistry;\n";
await writeFile(
  path.join(
    apiRoot,
    "src/lib/generated/plugin-host-modules.schema.generated.ts",
  ),
  source,
);
console.log(
  `Generated ${Object.keys(registry).length} public host module records from canonical configuration and API exports.`,
);
